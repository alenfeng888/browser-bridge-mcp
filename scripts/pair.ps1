# pair.ps1 - one-time pairing between the extension and the resident server.
#
# Generates a random shared secret, writes it to:
#   1. ~/.ext_bridge_ext_token            (server side, /extension/* gate)
#   2. extension/config.js                (extension side, gitignored)
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File scripts\pair.ps1              # default port 18795
#   powershell -ExecutionPolicy Bypass -File scripts\pair.ps1 -Port 18895  # custom port
#
# After pairing, reload the extension in edge://extensions.

param(
  [int]$Port = 18795
)

$ErrorActionPreference = 'Stop'

$extDir = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$extensionDir = Join-Path $extDir 'extension'

# 32 random bytes as hex
$rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
$bytes = New-Object byte[] 32
$rng.GetBytes($bytes)
$token = ($bytes | ForEach-Object { $_.ToString('x2') }) -join ''

# 1. server-side token file
$tokenFile = Join-Path $HOME '.ext_bridge_ext_token'
[System.IO.File]::WriteAllText($tokenFile, $token)

# 2. extension config (gitignored)
$configJs = "// Auto-generated by scripts/pair.ps1 - do not commit.`r`n" +
           "const BRIDGE_CONFIG = { httpBase: 'http://127.0.0.1:$Port', extToken: '$token' };`r`n"
[System.IO.File]::WriteAllText((Join-Path $extensionDir 'config.js'), $configJs)

Write-Host "[pair] wrote $tokenFile"
Write-Host "[pair] wrote $extensionDir\config.js (httpBase http://127.0.0.1:$Port)"
Write-Host "[pair] Now reload the extension in edge://extensions."
