// OpenCode Browser Bridge - MV3 service worker
//
// Two transports, no offscreen document:
//
//   1) HTTP long-poll queue  - service worker polls /extension/next on the
//      resident server.js and posts results back. Commands sit in a
//      server-side queue, so nothing is lost while this worker is asleep.
//
//   2) Native Messaging      - serves the Python router (serve.py). Held open
//      unconditionally as a second, independent path.
//
// Why no offscreen: an earlier version parked the WebSocket in an offscreen
// document. It reconnected every ~5s (server log: repeated
// "Extension connected" / "dropped stale extension socket") and left
// half-dead sockets behind. The queue has been steady, so offscreen is gone.

importScripts('bridge-core.js');
// Optional local config, generated by scripts/pair.ps1 (never committed):
//   const BRIDGE_CONFIG = { httpBase: 'http://127.0.0.1:18795', extToken: '<hex>' };
// Without it we fall back to the default port and no secret - the server keeps
// /extension/* open until the first correctly-paired extension checks in.
try { importScripts('config.js'); } catch (e) {}

const NM_HOST = 'ext_bridge';

let nmPort = null;
let nmUp = false;
let lastError = null;
let nativeRetries = 0;

// ── HTTP command queue (route 1) ──────────────────────────────────────

const BRIDGE_HTTP = (typeof BRIDGE_CONFIG !== 'undefined' && BRIDGE_CONFIG.httpBase) || 'http://127.0.0.1:18795';
// Shared secret for /extension/*; generated by scripts/pair.ps1, which writes
// the same value to ~/.ext_bridge_ext_token (server side) and config.js (here).
const BRIDGE_EXT_TOKEN = (typeof BRIDGE_CONFIG !== 'undefined' && BRIDGE_CONFIG.extToken) || '';
let polling = false;
// Heartbeat + generation guard. 回执 v2 P0: a dead poll loop left `polling`
// true forever, so every wake event hit `if (polling) return` and the queue
// went silent (waiters:0, pending piling up) until a manual re-reload.
// Now each loop beats and carries a generation; startPolling() only skips
// when the CURRENT generation's loop has beaten recently.
const POLL_STALE_MS = 30000;
let pollGen = 0;
let lastPollBeat = 0;

async function pollOnce() {
  const res = await fetch(`${BRIDGE_HTTP}/extension/next?clientId=sw`, {
    cache: 'no-store',
    headers: { 'x-bridge-ext': BRIDGE_EXT_TOKEN },
  });
  if (!res.ok) return false;
  const cmd = await res.json();
  if (!cmd || cmd.empty || !cmd.id) return false;

  let payload;
  try {
    const result = await BridgeCore.handleCommand({ method: cmd.method, params: cmd.params });
    payload = { id: cmd.id, result };
  } catch (err) {
    payload = { id: cmd.id, error: String(err?.message || err) };
  }
  try {
    await fetch(`${BRIDGE_HTTP}/extension/result`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'x-bridge-ext': BRIDGE_EXT_TOKEN },
      body: JSON.stringify(payload),
    });
  } catch {}
  return true;
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function pollLoop() {
  const gen = ++pollGen;
  while (gen === pollGen) {
    lastPollBeat = Date.now();
    try {
      // true  = we just ran a command; go straight back for the next one.
      // false = long poll came back empty (or was rejected); breathe first so
      //         a 403/500 cannot turn into a tight hammering loop.
      const didWork = await pollOnce();
      lastPollBeat = Date.now();
      if (!didWork) await sleep(1000);
    } catch {
      lastPollBeat = Date.now();
      await sleep(2000);
    }
  }
}

function startPolling() {
  const loopAlive = polling && Date.now() - lastPollBeat < POLL_STALE_MS;
  if (loopAlive) return;
  // Either never started, or the previous loop is dead/stale: bump the
  // generation (the old loop, if it is merely stuck rather than dead, will
  // see its generation replaced and exit), then start a fresh one.
  polling = true;
  pollLoop();
}

// ── Native Messaging (route 2) ────────────────────────────────────────

function ensureNative() {
  if (nmUp && nmPort) return true;
  try {
    nmPort = chrome.runtime.connectNative(NM_HOST);
  } catch (e) {
    lastError = String((e && e.message) || e);
    nmUp = false;
    return false;
  }
  nmPort.onMessage.addListener(async (msg) => {
    nmUp = true;
    nativeRetries = 0;
    if (!msg || !(msg.cmd || msg.method)) return;
    try {
      const result = await BridgeCore.handleCommand(msg);
      nmPort.postMessage({ id: msg.id, result });
    } catch (err) {
      nmPort.postMessage({ id: msg.id, error: String(err?.message || err) });
    }
  });
  nmPort.onDisconnect.addListener(() => {
    nmUp = false;
    nmPort = null;
    lastError = chrome.runtime.lastError
      ? String(chrome.runtime.lastError.message)
      : 'native host disconnected';
    // back off a bit: the host exits instantly when serve.py is not running
    const delay = Math.min(2000 * ++nativeRetries, 30000);
    setTimeout(() => { if (!nmUp) ensureNative(); }, delay);
  });
  nmUp = true;
  return true;
}

// ── Boot / keepalive ──────────────────────────────────────────────────

async function boot(force = false) {
  startPolling();
  ensureNative();
  if (force) {
    try { nmPort?.disconnect(); } catch {}
    nmUp = false;
    ensureNative();
  }
}

chrome.runtime.onInstalled.addListener(() => boot(true));
chrome.runtime.onStartup.addListener(() => boot(true));

// User activity in the browser is a free wake-up: MV3 restarts the worker to
// deliver these, which closes most of the gap left by the 1-minute alarm
// floor. Both handlers are idempotent (startPolling / ensureNative guard).
try {
  const wake = () => { startPolling(); ensureNative(); };
  chrome.tabs.onActivated.addListener(wake);
  chrome.tabs.onUpdated.addListener((_id, info) => {
    if (info.status === 'complete') wake();
  });
  chrome.windows.onFocusChanged.addListener(wake);
} catch (e) {
  console.error('[bridge] tab wake listeners failed:', e);
}

// alarms are the only reliable MV3 wake-up; 1 minute is the minimum period.
try {
  chrome.alarms.create('bridge-keepalive', { periodInMinutes: 1 });
  chrome.alarms.onAlarm.addListener((alarm) => {
    if (alarm.name !== 'bridge-keepalive') return;
    boot(false);
  });
} catch (e) {
  console.error('[bridge] alarms setup failed:', e);
}

// ── Popup API ─────────────────────────────────────────────────────────

chrome.runtime.onMessage.addListener((msg, _sender, reply) => {
  if (msg?.cmd === 'ping_status') {
    reply({ up: nmUp, nm: nmUp, polling, lastError });
    return true;
  }

  if (msg?.cmd === 'reconnect') {
    boot(true);
    setTimeout(() => reply({ up: nmUp, nm: nmUp, polling, lastError }), 1500);
    return true;
  }

  if (msg?.cmd === 'call') {
    BridgeCore.handleCommand({ method: msg.method, params: msg.params })
      .then((r) => reply({ ok: true, result: r }))
      .catch((e) => reply({ ok: false, error: String(e?.message || e) }));
    return true;
  }

  return false;
});

boot(true);
